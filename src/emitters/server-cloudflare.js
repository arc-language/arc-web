'use strict'

// Cloudflare Workers emitter.
// Input:  Arc program with RouteDecl + ModelDecl + JobDecl nodes
// Output: dist/worker.js  — CF Workers fetch + queue handler
//         dist/schema.sql — D1 CREATE TABLE statements (run via wrangler d1 execute)
//         wrangler.toml   — binding declarations (written alongside project)
//
// Key differences from Bun target:
//   - HTTP: `export default { fetch(req, env, ctx) }` instead of Bun.serve()
//   - DB:   D1 bindings via env.DB.prepare(...).bind(...) instead of bun:sqlite
//   - Queue: CF Queues via env.QUEUE.send({job, args}) instead of in-process
//   - Sessions: Same signed-cookie approach (Web Crypto available in CF)

const { JsEmitter } = require('./js')
const { compileRoutes } = require('../compilers/route-compiler')
const { emitAuthPreamble } = require('./auth-helpers')
const { emitEmailPreamble } = require('./queue-helpers')

const _SAFE_IDENT = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/

class CloudflareEmitter {
  constructor(options = {}) {
    this.options = options
    this.jsEmitter = new JsEmitter(options)
  }

  // Returns { worker: string, schema: string }
  emitProgram(program) {
    const routes = program.declarations.filter(d => d.type === 'RouteDecl')
    const schemas = program.declarations.filter(d => d.type === 'ModelDecl')
    const jobs = program.declarations.filter(d => d.type === 'JobDecl')
    const hasAuth = routes.some(r => r.annotations?.includes('@auth'))

    if (routes.length === 0 && schemas.length === 0) return { worker: '', schema: '' }

    const parts = []

    parts.push(this.emitPreamble())
    if (hasAuth) parts.push(emitAuthPreamble(this.options.auth ?? {}))
    parts.push(emitEmailPreamble())

    // For each schema, emit a D1-based db helper factory (no CREATE TABLE inline — use schema.sql)
    if (schemas.length > 0) {
      parts.push(this.emitD1Helpers(schemas))
    }

    // Job handlers (accept env as last param for D1 + Queue access)
    for (const job of jobs) {
      parts.push(this.emitJobHandler(job, schemas))
    }

    // Route handlers (accept env as last param)
    for (const route of routes) {
      parts.push(this.emitRouteHandler(route, schemas))
    }

    // Compile route trie with env threading
    const routeSpecs = routes.map(r => ({
      method: r.method,
      path: r.path,
      handlerName: this.routeHandlerName(r),
    }))
    parts.push(compileRoutes(routeSpecs, { extraParam: 'env' }))

    // CF Worker export
    parts.push(this.emitWorkerExport(jobs))

    const worker = parts.filter(Boolean).join('\n\n')

    // Schema SQL (for wrangler d1 execute)
    const schema = this.emitSchemaSql(schemas)

    return { worker, schema }
  }

  // ── Preamble ──────────────────────────────────────────────────────────────────

  emitPreamble() {
    return `
// Generated by Arc compiler — do not edit
// Target: Cloudflare Workers + D1

// Response helpers
const _json = (data, status = 200, headers = {}) =>
  new Response(JSON.stringify(data), {
    status,
    headers: { 'Content-Type': 'application/json', ...headers }
  })

const _html = (body, status = 200) =>
  new Response(body, { status, headers: { 'Content-Type': 'text/html; charset=utf-8' } })

const _text = (body, status = 200) =>
  new Response(body, { status, headers: { 'Content-Type': 'text/plain; charset=utf-8' } })

const _redirect = (location, status = 302) =>
  new Response(null, { status, headers: { Location: location } })

async function _parseBody(req) {
  const ct = req.headers.get('content-type') ?? ''
  if (ct.includes('application/json')) return req.json()
  if (ct.includes('application/x-www-form-urlencoded')) {
    const text = await req.text()
    return Object.fromEntries(new URLSearchParams(text))
  }
  if (ct.includes('multipart/form-data')) {
    const fd = await req.formData()
    return Object.fromEntries(fd.entries())
  }
  return {}
}`.trim()
  }

  // ── D1 helpers ────────────────────────────────────────────────────────────────

  emitD1Helpers(schemas) {
    const blocks = schemas.map(schema => this.emitD1ModelHelpers(schema))
    return `
// D1 database helpers — built per-request from env.DB
function _makeDb(D1) {
${blocks.join('\n')}
  return { ${schemas.map(s => s.name.toLowerCase() + 's').join(', ')} }
}`.trim()
  }

  emitD1ModelHelpers(schema) {
    const name = schema.name
    if (!_SAFE_IDENT.test(name)) throw new Error(`Arc codegen: unsafe schema name: ${JSON.stringify(name)}`)

    const lc = name.toLowerCase() + 's'
    const fields = (schema.fields ?? []).filter(f => f.name && !f.decorators?.includes('@id'))
    const colList = fields.map(f => f.name).join(', ')
    const placeholders = fields.map(() => '?').join(', ')
    const updates = fields.map(f => `${f.name} = ?`).join(', ')
    const fieldArgs = fields.map(f => `data.${f.name}`)

    return `
  const ${lc} = {
    findMany: async () => (await D1.prepare('SELECT * FROM ${lc}').all()).results,
    find: async (id) => D1.prepare('SELECT * FROM ${lc} WHERE id = ?').bind(id).first(),
    ${colList ? `create: async (data) => D1.prepare('INSERT INTO ${lc} (${colList}) VALUES (${placeholders}) RETURNING *').bind(${fieldArgs.join(', ')}).first(),` : ''}
    ${colList ? `update: async (id, data) => D1.prepare('UPDATE ${lc} SET ${updates} WHERE id = ? RETURNING *').bind(${fieldArgs.join(', ')}, id).first(),` : ''}
    delete: async (id) => (await D1.prepare('DELETE FROM ${lc} WHERE id = ?').bind(id).run(), true),
    count: async () => (await D1.prepare('SELECT COUNT(*) as count FROM ${lc}').first())?.count ?? 0,
  }`.trim()
  }

  // ── Schema SQL (for wrangler d1 execute) ──────────────────────────────────────

  emitSchemaSql(schemas) {
    return schemas.map(schema => {
      const lc = schema.name.toLowerCase() + 's'
      const fields = (schema.fields ?? []).filter(f => f.name && !f.decorators?.includes('@id'))
      const colDefs = [
        'id INTEGER PRIMARY KEY AUTOINCREMENT',
        ...fields.map(f => `${f.name} ${this.arcTypeToSql(f.typeAnnotation?.name)}`)
      ].join(',\n  ')
      return `CREATE TABLE IF NOT EXISTS ${lc} (\n  ${colDefs}\n);`
    }).join('\n\n')
  }

  arcTypeToSql(arcType) {
    switch (arcType) {
      case 'Int':      return 'INTEGER'
      case 'Float':    return 'REAL'
      case 'Bool':     return 'INTEGER'
      case 'DateTime': return 'TEXT'
      case 'Email':    return 'TEXT'
      case 'String':   return 'TEXT'
      default:         return 'TEXT'
    }
  }

  // ── Job handlers ──────────────────────────────────────────────────────────────

  routeHandlerName(route) {
    const slug = route.path.replace(/[^a-zA-Z0-9]/g, '_').replace(/^_+|_+$/g, '') || 'root'
    return `_route_${route.method.toLowerCase()}_${slug}`
  }

  emitJobHandler(job, schemas) {
    if (!_SAFE_IDENT.test(job.name)) throw new Error(`Arc codegen: unsafe job name: ${JSON.stringify(job.name)}`)
    const params = (job.params ?? []).map(p => p.name).join(', ')
    const body = job.body?.type === 'BlockStatement'
      ? this.jsEmitter.emitBody(job.body.body)
      : ''
    const hasDb = schemas.length > 0

    return `
// Job: ${job.name}
async function _job_${job.name}(${params}${params ? ', ' : ''}env) {
  ${hasDb ? 'const db = _makeDb(env.DB)' : ''}
  const Queue = { enqueue: (job, ...args) => env.QUEUE?.send({ job, args }) }
  const email = ${this._emailHelper()}
  ${body}
}`.trim()
  }

  // ── Route handlers ────────────────────────────────────────────────────────────

  emitRouteHandler(route, schemas) {
    const name = this.routeHandlerName(route)
    const pathParams = (route.params ?? []).map(p => `const ${p} = params['${p}']`).join('\n    ')
    const requiresAuth = route.annotations?.includes('@auth')
    const hasDb = schemas.length > 0

    const body = route.body?.type === 'BlockStatement'
      ? this.jsEmitter.emitBody(route.body.body)
      : ''

    const authGuard = requiresAuth
      ? `const _sess = await auth.session(req); if (!_sess) return _json({ error: 'Unauthorized' }, 401);\n    const session = _sess;`
      : ''

    return `
// Route: ${route.method} ${route.path}${requiresAuth ? ' [auth]' : ''}
async function ${name}(req, params, env) {
  try {
    ${hasDb ? 'const db = _makeDb(env.DB)' : ''}
    ${pathParams ? pathParams + '\n    ' : ''}${authGuard ? authGuard + '\n    ' : ''}const json = (data, status = 200) => _json(data, status)
    const html = (body, status = 200) => _html(body, status)
    const text = (body, status = 200) => _text(body, status)
    const redirect = (loc, status = 302) => _redirect(loc, status)
    const parseBody = async (req) => _parseBody(req)
    const request = req
    const Queue = { enqueue: (job, ...args) => env.QUEUE?.send({ job, args }) }
    const email = ${this._emailHelper()}
    ${body}
  } catch (_e) {
    if (_e?._authError) return _json({ error: 'Unauthorized' }, 401)
    console.error('[arc] route ${route.method} ${route.path} error:', _e)
    return _json({ error: 'Internal server error' }, 500)
  }
}`.trim()
  }

  _emailHelper() {
    return `{
      send: async (opts) => {
        const key = typeof env !== 'undefined' ? env.RESEND_API_KEY : undefined
        const apiKey = key ?? process.env?.RESEND_API_KEY
        if (!apiKey) { console.warn('[arc:email] Set RESEND_API_KEY binding'); return }
        await fetch('https://api.resend.com/emails', {
          method: 'POST',
          headers: { Authorization: \`Bearer \${apiKey}\`, 'Content-Type': 'application/json' },
          body: JSON.stringify({ from: opts.from ?? 'noreply@example.com', to: Array.isArray(opts.to) ? opts.to : [opts.to], subject: opts.subject, text: opts.text, html: opts.html }),
        })
      }
    }`
  }

  // ── CF Worker export ──────────────────────────────────────────────────────────

  emitWorkerExport(jobs) {
    const jobRegistry = jobs.length > 0
      ? `const _jobRegistry = {\n${jobs.map(j => `  '${j.name}': _job_${j.name},`).join('\n')}\n}`
      : 'const _jobRegistry = {}'

    const queueHandler = jobs.length > 0 ? `
  async queue(batch, env) {
    for (const msg of batch.messages) {
      const { job, args = [] } = msg.body
      const fn = _jobRegistry[job]
      if (fn) {
        try { await fn(...args, env); msg.ack() } catch (e) { console.error('[arc:queue]', e); msg.retry() }
      } else {
        msg.ack()
      }
    }
  },` : ''

    return `
${jobRegistry}

export default {
  async fetch(req, env, ctx) {
    const url = new URL(req.url)
    if (url.pathname === '/health') return new Response(JSON.stringify({ status: 'ok' }), { headers: { 'Content-Type': 'application/json' } })
    return _dispatch(req, url, env)
  },${queueHandler}
}`.trim()
  }
}

module.exports = { CloudflareEmitter }
