'use strict'

// Cloudflare Workers emitter.
// Input:  Arc program with RouteDecl + ModelDecl + JobDecl nodes
// Output: dist/worker.js  - CF Workers fetch + queue handler
//         dist/schema.sql - D1 CREATE TABLE statements (run via wrangler d1 execute)
//         wrangler.toml   - binding declarations (written alongside project)
//
// Key differences from Bun target:
//   - HTTP: `export default { fetch(req, env, ctx) }` instead of Bun.serve()
//   - DB:   D1 bindings via env.DB.prepare(...).bind(...) instead of bun:sqlite
//   - Queue: CF Queues via env.QUEUE.send({job, args}) instead of in-process
//   - Sessions: Same signed-cookie approach (Web Crypto available in CF)

const { JsEmitter } = require('./js')
const { compileRoutes } = require('../compilers/route-compiler')
const { emitAuthPreamble } = require('./auth-helpers')
const { emitEmailPreamble } = require('./queue-helpers')
const { arcTypeToSql: _arcTypeToSql } = require('../compilers/sql-types')
const { routeHandlerName } = require('./route-utils')
const { SHARED_RESPONSE_HELPERS } = require('./emitter-preamble')
const { emitRouteBody } = require('./route-body-emitter')

const _SAFE_IDENT = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/

class CloudflareEmitter {
  constructor(options = {}) {
    this.options = options
    this.jsEmitter = new JsEmitter(options)
  }

  // Returns { worker: string, schema: string }
  emitProgram(program) {
    const routes = program.declarations.filter(d => d.type === 'RouteDecl')
    const schemas = program.declarations.filter(d => d.type === 'ModelDecl')
    const jobs = program.declarations.filter(d => d.type === 'JobDecl')
    const hasAuth = routes.some(r => r.annotations?.some(a => a === '@auth' || a.startsWith('@auth(')))

    if (routes.length === 0 && schemas.length === 0) return { worker: '', schema: '' }

    const parts = []

    parts.push(this.emitPreamble())
    if (hasAuth) parts.push(emitAuthPreamble(this.options.auth ?? {}))
    parts.push(emitEmailPreamble())
    parts.push(this.emitEmailHelper())

    // For each schema, emit a D1-based db helper factory (no CREATE TABLE inline - use schema.sql)
    if (schemas.length > 0) {
      parts.push(this.emitD1Helpers(schemas))
    }

    // Job handlers (accept env as last param for D1 + Queue access)
    for (const job of jobs) {
      parts.push(this.emitJobHandler(job, schemas))
    }

    // Route handlers (accept env as last param)
    for (const route of routes) {
      parts.push(this.emitRouteHandler(route, schemas))
    }

    // Compile route trie with env threading
    const routeSpecs = routes.map(r => ({
      method: r.method,
      path: r.path,
      handlerName: routeHandlerName(r),
    }))
    parts.push(compileRoutes(routeSpecs, { extraParam: 'env' }))

    // CF Worker export
    parts.push(this.emitWorkerExport(jobs, schemas))

    const worker = parts.filter(Boolean).join('\n\n')

    // Schema SQL (for wrangler d1 execute)
    const schema = this.emitSchemaSql(schemas)

    return { worker, schema }
  }

  // ── Preamble ──────────────────────────────────────────────────────────────────

  emitPreamble() {
    return `
// Generated by Arc compiler — do not edit
// Target: Cloudflare Workers + D1

const _CORS_ORIGIN = null

${SHARED_RESPONSE_HELPERS}

// In-memory rate limiter — 60 mutating requests per IP per minute (sliding window)
// Uses the global isolate scope (persists across requests within the same isolate instance).
// No setInterval: CF isolates don't guarantee timer firing across requests. Instead, expired
// entries are purged lazily when the Map exceeds 10k entries to bound memory.
const _rlMap = new Map()
function _checkRateLimit(req) {
  if (req.method !== 'POST' && req.method !== 'PUT' && req.method !== 'DELETE' && req.method !== 'PATCH') return null
  // cf-connecting-ip is set by CF infrastructure and is not forgeable by clients.
  // XFF is client-controlled and is NOT trusted here — use 'unknown' if cf-connecting-ip absent.
  const ip = req.headers.get('cf-connecting-ip') ?? 'unknown'
  const now = Date.now()
  const window = 60000
  if (_rlMap.size > 10000) {
    for (const [k, v] of _rlMap) if (now > v.resetAt) _rlMap.delete(k)
  }
  let entry = _rlMap.get(ip)
  if (!entry || now > entry.resetAt) { entry = { count: 0, resetAt: now + window }; _rlMap.set(ip, entry) }
  entry.count++
  if (entry.count > 60) return _json({ error: 'Too many requests' }, 429, { 'Retry-After': String(Math.ceil((entry.resetAt - now) / 1000)) })
  return null
}

// Hoisted: avoids per-request RegExp allocation at high request rates
const _TRACE_ID_RE = /^[a-zA-Z0-9_-]{1,64}$/

// Route context factory — extracts the common per-request setup shared by every handler
function _routeCtx(req, env) {
  const _clientId = req.headers.get('x-request-id') ?? ''
  const traceId = _TRACE_ID_RE.test(_clientId) ? _clientId : crypto.randomUUID()
  return {
    traceId,
    json: (data, status = 200) => _json(data, status),
    html: (body, status = 200) => _html(body, status),
    text: (body, status = 200) => _text(body, status),
    redirect: (loc, status = 302) => _redirect(loc, status),
    parseBody: () => _parseBody(req),
    request: req,
    Queue: { enqueue: (job, ...args) => { if (!env.QUEUE) { console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', msg: '[arc:queue] env.QUEUE binding not configured — add a Queue binding in wrangler.toml', job })); throw new Error('[arc:queue] env.QUEUE binding not configured') } return env.QUEUE.send({ job, args }) } },
  }
}`.trim()
  }

  // ── D1 helpers ────────────────────────────────────────────────────────────────

  emitD1Helpers(schemas) {
    const blocks = schemas.map(schema => this.emitD1ModelHelpers(schema))
    return `
// D1 database helpers — cached per D1 binding instance to avoid per-request allocation
const _dbCache = new WeakMap()
function _getDb(D1) {
  if (!D1) throw new Error('[arc] env.DB is not bound — add a D1 binding named DB in wrangler.toml')
  let db = _dbCache.get(D1)
  if (!db) { db = _makeDb(D1); _dbCache.set(D1, db) }
  return db
}
function _makeDb(D1) {
${blocks.join('\n')}
  return { ${schemas.map(s => s.name.toLowerCase() + 's').join(', ')} }
}`.trim()
  }

  emitD1ModelHelpers(schema) {
    const name = schema.name
    if (!_SAFE_IDENT.test(name)) throw new Error(`Arc codegen: unsafe schema name: ${JSON.stringify(name)}`)

    const lc = name.toLowerCase() + 's'
    const fields = (schema.fields ?? []).filter(f => f.name && !f.decorators?.includes('@id'))
    for (const f of fields) {
      if (!_SAFE_IDENT.test(f.name)) throw new Error(`Arc codegen: unsafe field name: ${JSON.stringify(f.name)}`)
    }
    const colList = fields.map(f => f.name).join(', ')
    const selectCols = colList ? `id, ${colList}` : 'id'
    const placeholders = fields.map((_, i) => `?${i + 1}`).join(', ')
    const updates = fields.map((f, i) => `${f.name} = ?${i + 1}`).join(', ')
    const fieldNames = JSON.stringify(fields.map(f => f.name))
    const requiredFieldNames = JSON.stringify(
      fields
        .filter(f => !(f.typeAnnotation?.nullable === true || (f.typeAnnotation?.name ?? '').endsWith('?') || f.optional === true || f.init != null))
        .map(f => f.name)
    )
    const fieldArgs = fields.map(f => `_d.${f.name}`)

    return `
  const _${lc}_flds = ${fieldNames}
  const _${lc}_req = ${requiredFieldNames}
  const ${lc} = {
    findMany: async (opts = {}) => (await D1.prepare('SELECT ${selectCols} FROM ${lc} LIMIT ?1 OFFSET ?2').bind(Math.min(opts?.limit ?? 20, 100), opts?.offset ?? 0).all()).results,
    find: async (id) => D1.prepare('SELECT ${selectCols} FROM ${lc} WHERE id = ?1').bind(id).first(),
    ${colList ? `create: async (data) => { const _d = _pick(data, _${lc}_flds); const _miss = _${lc}_req.filter(k => _d[k] == null); if (_miss.length) throw Object.assign(new Error('${lc}.create: missing required fields: ' + _miss.join(', ')), { status: 422 }); return D1.prepare('INSERT INTO ${lc} (${colList}) VALUES (${placeholders}) RETURNING *').bind(${fieldArgs.join(', ')}).first() },` : ''}
    ${colList ? `update: async (id, data) => { const _d = _pick(data, _${lc}_flds); return D1.prepare('UPDATE ${lc} SET ${updates} WHERE id = ?${fields.length + 1} RETURNING *').bind(${fieldArgs.join(', ')}, id).first() },` : ''}
    delete: async (id) => (await D1.prepare('DELETE FROM ${lc} WHERE id = ?1').bind(id).run(), true),
    count: async () => (await D1.prepare('SELECT COUNT(*) as count FROM ${lc}').first())?.count ?? 0,
  }`.trim()
  }

  // ── Schema SQL (for wrangler d1 execute) ──────────────────────────────────────

  emitSchemaSql(schemas) {
    return schemas.map(schema => {
      const lc = schema.name.toLowerCase() + 's'
      const fields = (schema.fields ?? []).filter(f => f.name && !f.decorators?.includes('@id'))
      const colDefs = [
        'id INTEGER PRIMARY KEY AUTOINCREMENT',
        ...fields.map(f => `${f.name} ${_arcTypeToSql(f.typeAnnotation?.name, 'sqlite')}`)
      ].join(',\n  ')
      return `CREATE TABLE IF NOT EXISTS ${lc} (\n  ${colDefs}\n);`
    }).join('\n\n')
  }

  // ── Job handlers ──────────────────────────────────────────────────────────────

  emitJobHandler(job, schemas) {
    if (!_SAFE_IDENT.test(job.name)) throw new Error(`Arc codegen: unsafe job name: ${JSON.stringify(job.name)}`)
    const params = (job.params ?? []).map(p => p.name).join(', ')
    const body = job.body?.type === 'BlockStatement'
      ? emitRouteBody(job.body.body, this.jsEmitter)
      : ''
    const hasDb = schemas.length > 0

    return `
// Job: ${job.name}
async function _job_${job.name}(${params}${params ? ', ' : ''}env) {
  ${hasDb ? 'const db = _getDb(env.DB)' : ''}
  const Queue = { enqueue: (job, ...args) => { if (!env.QUEUE) { console.warn(JSON.stringify({ ts: new Date().toISOString(), level: 'warn', msg: '[arc:queue] env.QUEUE binding not configured — job dropped', job })); return Promise.resolve({ ok: false, error: 'queue_not_configured' }) } return env.QUEUE.send({ job, args }) } }
  const email = ${this._emailHelper()}
  ${body}
}`.trim()
  }

  // ── Route handlers ────────────────────────────────────────────────────────────

  emitRouteHandler(route, schemas) {
    const name = routeHandlerName(route)
    const pathParams = (route.params ?? []).map(p => `const ${p} = params['${p}']`).join('\n    ')
    const authAnnotation = route.annotations?.find(a => a === '@auth' || a.startsWith('@auth('))
    const requiresAuth = !!authAnnotation
    let authRole = null
    if (authAnnotation) {
      const roleMatch = authAnnotation.match(/^@auth\(([^)]+)\)$/)
      if (roleMatch) authRole = roleMatch[1].trim()
    }
    const hasDb = schemas.length > 0

    const body = route.body?.type === 'BlockStatement'
      ? emitRouteBody(route.body.body, this.jsEmitter)
      : ''

    let authGuard = ''
    if (requiresAuth) {
      authGuard = `const _sess = await auth.session(req); if (!_sess) return _json({ error: 'Unauthorized' }, 401);\n    const session = _sess;`
      if (authRole) {
        const roles = authRole.split(',').map(r => r.trim()).filter(Boolean)
        authGuard += `\n    if (!${JSON.stringify(roles)}.includes(session.role)) return _json({ error: 'Forbidden' }, 403);`
      }
    }

    return `
// Route: ${route.method} ${route.path}${requiresAuth ? ' [auth]' : ''}
async function ${name}(req, params, env) {
  const { traceId: _traceId, json, html, text, redirect, parseBody, request, Queue } = _routeCtx(req, env)
  try {
    ${hasDb ? 'const db = _getDb(env.DB)' : ''}
    const email = ${this._emailHelper()}
    ${pathParams ? pathParams + '\n    ' : ''}${authGuard ? authGuard + '\n    ' : ''}${body}
  } catch (_e) {
    if (_e?._authError) return _json({ error: 'Unauthorized' }, 401)
    if (_e?.status === 413) return _json({ error: 'Request body too large' }, 413)
    if (_e?.status === 422) return _json({ error: _e.message ?? 'Unprocessable entity' }, 422)
    if (_e?.status === 400) return _json({ error: _e.message ?? 'Bad request' }, 400)
    console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', traceId: _traceId, method: '${route.method}', path: '${route.path}', msg: _e?.message ?? String(_e), stack: _e?.stack }))
    return _json({ error: 'Internal server error' }, 500)
  }
}`.trim()
  }

  emitEmailHelper() {
    return `
// Email helper — compiled once, shared across all handlers
function _makeEmail(env) {
  return {
    send: async (opts) => {
      const apiKey = env.RESEND_API_KEY
      if (!apiKey) { console.warn(JSON.stringify({ ts: new Date().toISOString(), level: 'warn', msg: '[arc:email] RESEND_API_KEY binding not set — email not sent' })); return }
      const _r = await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: { Authorization: \`Bearer \${apiKey}\`, 'Content-Type': 'application/json' },
        signal: AbortSignal.timeout(15000),
        body: JSON.stringify({ from: opts.from ?? 'noreply@example.com', to: Array.isArray(opts.to) ? opts.to : [opts.to], subject: opts.subject, text: opts.text, html: opts.html }),
      })
      if (!_r.ok) { const _errBody = await _r.text().catch(() => ''); console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', msg: \`[arc:email] Resend error: HTTP \${_r.status}\${_errBody ? ' — ' + _errBody.slice(0, 120) : ''}\` })); return { ok: false, error: 'HTTP ' + _r.status } }
      const _body = await _r.json().catch(() => ({}))
      return { ok: true, id: _body?.id }
    }
  }
}`.trim()
  }

  _emailHelper() {
    return '_makeEmail(env)'
  }

  // ── CF Worker export ──────────────────────────────────────────────────────────

  emitWorkerExport(jobs, schemas) {
    const jobRegistry = jobs.length > 0
      ? `const _jobRegistry = {\n${jobs.map(j => {
          if (!_SAFE_IDENT.test(j.name)) throw new Error(`Arc codegen: unsafe job name in registry: ${JSON.stringify(j.name)}`)
          return `  '${j.name}': _job_${j.name},`
        }).join('\n')}\n}`
      : 'const _jobRegistry = {}'

    // Per-job expected argument counts for queue message validation
    const jobArgCounts = jobs.length > 0
      ? `const _jobArgCounts = {\n${jobs.map(j => `  '${j.name}': ${(j.params ?? []).length},`).join('\n')}\n}`
      : 'const _jobArgCounts = {}'

    const queueHandler = jobs.length > 0 ? `
  async queue(batch, env, ctx) {
    for (const msg of batch.messages) {
      const { job, args: _rawArgs } = msg.body
      const args = Array.isArray(_rawArgs) ? _rawArgs : []
      const fn = _jobRegistry[job]
      if (fn) {
        const _expectedArgCount = _jobArgCounts[job] ?? -1
        if (_expectedArgCount !== -1 && args.length !== _expectedArgCount) {
          console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', queue: job, event: 'invalid_args', msg: \`expected \${_expectedArgCount} args, got \${args.length}\` }))
          try { msg.ack() } catch (_e) {}
          continue
        }
        try { await fn(...args, env) } catch (e) {
          console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', queue: job, msg: e?.message ?? String(e) }))
          try {
            if (msg.attempts >= 3) { console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', queue: job, event: 'dlq', msg: 'max retries exceeded' })); msg.ack() }
            else { msg.retry() }
          } catch (_ackErr) { console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', queue: job, event: 'ack_failed', msg: _ackErr?.message ?? String(_ackErr) })) }
          continue
        }
        try { msg.ack() } catch (_ackErr) { console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', queue: job, event: 'ack_failed', msg: _ackErr?.message ?? String(_ackErr) })) }
      } else {
        console.error(JSON.stringify({ ts: new Date().toISOString(), level: 'error', queue: job, event: 'unknown_job', msg: 'no handler registered — retrying so message is not silently lost' }))
        try { msg.retry() } catch (_e) { msg.ack() }
      }
    }
  },` : ''

    return `
${jobRegistry}
${jobArgCounts}

export default {
  async fetch(req, env, ctx) {
    const url = new URL(req.url)
    if (url.pathname === '/health') {
      try {
        let _dbOk = false
        if (env.DB) { try { await Promise.race([env.DB.prepare('SELECT 1').first(), new Promise((_, r) => setTimeout(() => r(new Error('timeout')), 2000))]); _dbOk = true } catch {} }
        else { _dbOk = true }
        return new Response(JSON.stringify({ status: _dbOk ? 'ok' : 'degraded', db: env.DB ? (_dbOk ? 'up' : 'down') : 'n/a', queue: env.QUEUE ? 'configured' : 'n/a', version: typeof __ARC_VERSION__ !== 'undefined' ? __ARC_VERSION__ : 'unknown', ts: new Date().toISOString() }), { status: _dbOk ? 200 : 503, headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store, no-cache' } })
      } catch (_he) { return new Response(JSON.stringify({ status: 'error' }), { status: 503, headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store, no-cache' } }) }
    }
    const _rl = _checkRateLimit(req)
    if (_rl) return _rl
    return _dispatch(req, url.pathname, env)
  },${queueHandler}
}`.trim()
  }
}

module.exports = { CloudflareEmitter }
