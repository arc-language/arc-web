async function scaffold(modelName, projectDir, opts = {}) {
  if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(modelName)) {
    console.error(`arc scaffold: invalid model name "${modelName}" — use letters, numbers, underscores starting with a letter`)
    process.exit(1)
  }
  const absDir = path.resolve(projectDir)
  const _t0 = Date.now()

  const model = _findModel(modelName, absDir)
  if (!model) {
    console.error(`arc scaffold: model "${modelName}" not found in ${path.relative(process.cwd(), absDir)}`)
    console.error(`  Define it in server/schemas/${modelName.toLowerCase()}.arc first`)
    process.exit(1)
  }

  const name = model.name
  const plural = _pluralize(name)
  const routesFile = path.join(absDir, 'server', 'admin', 'routes', `${plural}.arc`)
  const listFile   = path.join(absDir, 'admin', `${plural}.arc`)
  const formFile   = path.join(absDir, 'admin', `${name.toLowerCase()}-form.arc`)

  const existing = [routesFile, listFile, formFile].filter(f => fs.existsSync(f))
  if (existing.length > 0 && !opts.force) {
    for (const f of existing) {
      console.error(`arc scaffold: ${path.relative(process.cwd(), f)} already exists (--force to overwrite)`)
    }
    process.exit(1)
  }

  fs.mkdirSync(path.dirname(routesFile), { recursive: true })
  fs.mkdirSync(path.dirname(listFile), { recursive: true })

  fs.writeFileSync(routesFile, generateAdminRoutes(model))
  fs.writeFileSync(listFile, generateListPage(model))
  fs.writeFileSync(formFile, generateFormPage(model))

  const elapsed = Date.now() - _t0
  const rRel = path.relative(process.cwd(), routesFile)
  const lRel = path.relative(process.cwd(), listFile)
  const fRel = path.relative(process.cwd(), formFile)

  if (_C) {
    console.log(`\n  ${_CYAN}⚡ arc scaffold${_RST} ${name}  →  server/ + admin/\n`)
    console.log(`  ${_DIM}routes${_RST}  ${rRel}    ${_DIM}(5 routes)${_RST}`)
    console.log(`  ${_DIM}page  ${_RST}  ${lRel}   ${_DIM}(list · pagination)${_RST}`)
    console.log(`  ${_DIM}page  ${_RST}  ${fRel}   ${_DIM}(create form)${_RST}`)
    console.log(`\n  ${_GREEN}✓${_RST}  scaffold complete in ${_DIM}${elapsed}ms${_RST}`)
    console.log(`  ${_DIM}↳  arc build-server . && arc build-site admin/${_RST}\n`)
  } else {
    console.log(`arc scaffold: created ${rRel}`)
    console.log(`arc scaffold: created ${lRel}`)
    console.log(`arc scaffold: created ${fRel}`)
  }
}

async function scaffoldAll(projectDir, opts = {}) {
  const absDir = path.resolve(projectDir)
  const models = _findAllModels(absDir)
  if (models.length === 0) {
    console.error(`arc scaffold: no model declarations found in ${path.relative(process.cwd(), absDir)}`)
    process.exit(1)
  }
  for (const model of models) {
    await scaffold(model.name, projectDir, opts)
  }
}

