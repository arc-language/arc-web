function _pluralize(name) {
  const lower = name.toLowerCase()
  if (lower.endsWith('y') && !/[aeiou]y$/.test(lower)) return lower.slice(0, -1) + 'ies'
  if (lower.endsWith('s') || lower.endsWith('x') || lower.endsWith('z') || lower.endsWith('ch') || lower.endsWith('sh')) return lower + 'es'
  return lower + 's'
}

function _fieldToInputType(field) {
  const t = (field.typeAnnotation?.name ?? '').replace(/\?$/, '')
  if (t === 'Bool') return 'checkbox'
  if (t === 'Int' || t === 'Float') return 'number'
  if (t === 'DateTime') return 'datetime-local'
  if (t === 'Email') return 'email'
  if (t === 'Text') return 'textarea'
  return 'text'
}

function _parseFieldsArg(fieldsStr) {
  if (!fieldsStr) return [{ name: 'title', type: 'String', optional: false }, { name: 'body', type: 'Text', optional: false }]
  return fieldsStr.trim().split(/\s+/).map(part => {
    const optional = part.endsWith('?')
    const clean = optional ? part.slice(0, -1) : part
    const [name, type = 'String'] = clean.split(':')
    if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name)) {
      console.error(`arc scaffold: invalid field name "${name}" — use letters, numbers, underscores`)
      process.exit(1)
    }
    return { name, type, optional }
  })
}

function _editableFields(model) {
  return (model.fields ?? []).filter(f =>
    f.name && !f.decorators?.includes('@id')
  )
}

function _primaryField(model) {
  const fields = _editableFields(model)
  const strField = fields.find(f => {
    const t = (f.typeAnnotation?.name ?? '').replace(/\?$/, '')
    return t === 'String' || t === 'Email'
  })
  return (strField ?? fields[0])?.name ?? 'id'
}

function _findModel(modelName, absDir) {
  const serverDir = fs.existsSync(path.join(absDir, 'server'))
    ? path.join(absDir, 'server')
    : absDir
  for (const file of findArcFiles(serverDir)) {
    let src
    try { src = fs.readFileSync(file, 'utf8') }
    catch { continue }
    try {
      const tokens = new Lexer(src, file).tokenize()
      const program = new Parser(tokens, file).parse()
      const model = program.declarations.find(
        d => d.type === 'ModelDecl' && d.name.toLowerCase() === modelName.toLowerCase()
      )
      if (model) return model
    } catch { continue }
  }
  return null
}

function _findAllModels(absDir) {
  const serverDir = fs.existsSync(path.join(absDir, 'server'))
    ? path.join(absDir, 'server')
    : absDir
  const models = []
  for (const file of findArcFiles(serverDir)) {
    let src
    try { src = fs.readFileSync(file, 'utf8') }
    catch { continue }
    try {
      const tokens = new Lexer(src, file).tokenize()
      const program = new Parser(tokens, file).parse()
      models.push(...program.declarations.filter(d => d.type === 'ModelDecl'))
    } catch { continue }
  }
  return models
}

