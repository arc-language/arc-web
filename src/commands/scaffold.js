async function scaffoldBlockInit(projectDir) {
  const absDir = path.resolve(projectDir)
  const draftSrc = path.join(__dirname, '..', 'draft', 'arc-draft.js')

  const files = {
    [path.join(absDir, 'server', 'schemas', 'pageblock.arc')]: `model PageBlock
  @id let id       = autoincrement()
  let page         : String
  let type         : String
  let order        : Int = 0
  let visible      : Bool = true
  let data         : String = "{}"
  let updatedAt    : DateTime = now()

model DraftToken
  @id let id       = autoincrement()
  let token        : String
  let expiresAt    : DateTime
`,
    [path.join(absDir, 'server', 'admin', 'routes', 'blocks.arc')]: `# Block CRUD + draft token routes

@route @auth(admin,editor) get "/admin/blocks" -> Response
  const pageSlug = params.page ?? "home"
  json({ blocks: db.pageblocks.findMany({ where: { page: pageSlug }, orderBy: { order: "asc" } }) })

@route @auth(admin,editor) post "/admin/blocks" -> Response
  const body = parseBody(request)
  const maxOrder = db.pageblocks.count({ where: { page: body.page } })
  json(db.pageblocks.create({ ...body, order: maxOrder }), 201)

@route @auth(admin,editor) patch "/admin/blocks/:id" -> Response
  const body = parseBody(request)
  const block = db.pageblocks.find(params.id)
  match block
    None    -> json({ error: "not found" }, 404)
    Some(b) ->
      const merged = JSON.parse(b.data)
      for key, val in body.data
        merged[key] = val
      json(db.pageblocks.update(params.id, { data: JSON.stringify(merged), updatedAt: now() }))

@route @auth(admin,editor) patch "/admin/blocks/:id/reorder" -> Response
  const body = parseBody(request)
  const block = db.pageblocks.find(params.id)
  match block
    None    -> json({ error: "not found" }, 404)
    Some(b) ->
      const dir = body.direction
      const neighbor = dir == "up"
        ? db.pageblocks.findFirst({ where: { page: b.page, order: { lt: b.order } }, orderBy: { order: "desc" } })
        : db.pageblocks.findFirst({ where: { page: b.page, order: { gt: b.order } }, orderBy: { order: "asc" } })
      match neighbor
        None    -> json({ ok: false })
        Some(n) ->
          db.pageblocks.update(params.id, { order: n.order })
          db.pageblocks.update(n.id, { order: b.order })
          json({ ok: true })

@route @auth(admin) del "/admin/blocks/:id" -> Response
  db.pageblocks.delete(params.id)
  json({ ok: true })

@route @auth(admin,editor) get "/admin/api/block-types" -> Response
  json(loadBlockTypes())

@route @auth(admin,editor) post "/admin/api/draft-token" -> Response
  const raw = crypto.randomBytes(32).toString("hex")
  const expires = new Date(Date.now() + 8 * 3600 * 1000)
  db.drafttokens.create({ token: raw, expiresAt: expires })
  json({ token: raw })

@route get "/admin/api/draft" -> Response
  const token = params.token ?? ""
  const row = db.drafttokens.findFirst({ where: { token } })
  match row
    None    -> json({ valid: false })
    Some(t) -> json({ valid: new Date(t.expiresAt) > new Date() })

@route @auth(admin,editor) post "/admin/api/publish" -> Response
  json({ ok: true, publishedAt: now() })
`,
    [path.join(absDir, 'server', 'block-types.json')]: '{}',
    [path.join(absDir, 'admin', 'blocks.arc')]: generateBlocksAdminPage(),
  }

  const existing = Object.keys(files).filter(f => fs.existsSync(f))
  if (existing.length > 0) {
    for (const f of existing) console.error(`arc scaffold block --init: ${path.relative(process.cwd(), f)} already exists`)
    process.exit(1)
  }

  for (const [dest, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.writeFileSync(dest, content)
  }

  // Copy draft script to public/
  const publicDraft = path.join(absDir, 'public', 'arc-draft.js')
  fs.mkdirSync(path.dirname(publicDraft), { recursive: true })
  if (fs.existsSync(draftSrc)) {
    fs.copyFileSync(draftSrc, publicDraft)
  }

  if (_C) {
    console.log(`\n  ${_CYAN}⚡ arc scaffold block --init${_RST}\n`)
    for (const f of [...Object.keys(files), publicDraft]) {
      console.log(`  ${_GREEN}+${_RST} ${path.relative(process.cwd(), f)}`)
    }
    console.log(`\n  ${_DIM}↳  next: arc scaffold block <Type> --fields "title:String body:Text"${_RST}\n`)
  } else {
    for (const f of Object.keys(files)) console.log(`arc scaffold block --init: created ${path.relative(process.cwd(), f)}`)
  }
}

async function scaffoldBlock(type, projectDir, opts = {}) {
  const absDir = path.resolve(projectDir)
  const typesFile = path.join(absDir, 'server', 'block-types.json')

  if (!fs.existsSync(typesFile)) {
    console.error(`arc scaffold block: server/block-types.json not found — run arc scaffold block --init first`)
    process.exit(1)
  }

  const typeKey = type.toLowerCase()
  if (!/^[a-z][a-z0-9_-]*$/.test(typeKey)) {
    console.error(`arc scaffold block: invalid block type name "${type}" — use lowercase letters, numbers, hyphens, underscores`)
    process.exit(1)
  }
  const fields = _parseFieldsArg(opts.fields)

  // Update block-types.json — use a lock file to prevent concurrent write races
  const lockFile = typesFile + '.lock'
  let lockAcquired = false
  try {
    fs.writeFileSync(lockFile, String(process.pid), { flag: 'wx' })
    lockAcquired = true
  } catch (e) {
    if (e.code === 'EEXIST') {
      console.error(`arc scaffold block: another scaffold is running — remove ${path.relative(process.cwd(), lockFile)} if stale`)
      process.exit(1)
    }
    throw e
  }
  // Release lock on unexpected exit (SIGINT/SIGTERM or unhandled error)
  const _lockRelease = () => { if (!lockAcquired) return; lockAcquired = false; try { fs.unlinkSync(lockFile) } catch {} }
  process.once('exit', _lockRelease)
  process.once('SIGINT', () => { _lockRelease(); process.exit(130) })
  process.once('SIGTERM', () => { _lockRelease(); process.exit(143) })
  let registry
  try {
    registry = JSON.parse(fs.readFileSync(typesFile, 'utf8'))
  } catch (e) {
    console.error(`arc scaffold block: invalid JSON in server/block-types.json: ${e.message}`)
    fs.unlinkSync(lockFile)
    process.exit(1)
  }
  if (registry[typeKey] && !opts.force) {
    console.error(`arc scaffold block: block type "${typeKey}" already exists (--force to overwrite)`)
    fs.unlinkSync(lockFile)
    process.exit(1)
  }
  registry[typeKey] = {
    label: type.charAt(0).toUpperCase() + type.slice(1).replace(/([A-Z])/g, ' $1').trim(),
    fields: fields.map(f => ({ name: f.name, type: f.type, label: f.name.replace(/([A-Z])/g, ' $1').replace(/^./, s => s.toUpperCase()), ...(f.optional ? { optional: true } : {}) }))
  }
  try {
    fs.writeFileSync(typesFile, JSON.stringify(registry, null, 2))
  } catch (e) {
    lockAcquired = false
    fs.unlinkSync(lockFile)
    console.error(`arc scaffold block: failed to write ${path.relative(process.cwd(), typesFile)}: ${e.message}`)
    process.exit(1)
  }
  lockAcquired = false
  fs.unlinkSync(lockFile)

  const editorFile = path.join(absDir, 'admin', 'blocks', `${typeKey}.arc`)
  const widgetFile = path.join(absDir, 'site', 'blocks', `${typeKey}.arc`)

  try {
    fs.mkdirSync(path.dirname(editorFile), { recursive: true })
    fs.mkdirSync(path.dirname(widgetFile), { recursive: true })
    fs.writeFileSync(editorFile, generateBlockEditorPage(typeKey, fields))
    fs.writeFileSync(widgetFile, generateBlockWidget(typeKey, fields))
  } catch (e) {
    console.error(`arc scaffold block: failed to write generated files: ${e.message}`)
    process.exit(1)
  }

  if (_C) {
    console.log(`\n  ${_CYAN}⚡ arc scaffold block${_RST} ${type}\n`)
    console.log(`  ${_GREEN}~${_RST} ${path.relative(process.cwd(), typesFile)}   (updated)`)
    console.log(`  ${_GREEN}+${_RST} ${path.relative(process.cwd(), editorFile)}`)
    console.log(`  ${_GREEN}+${_RST} ${path.relative(process.cwd(), widgetFile)}`)
    console.log(`\n  ${_DIM}widget: <${type.charAt(0).toUpperCase() + type.slice(1)}Block id=... type="${typeKey}" ...fields />`)
    console.log(`  ↳  add data-block-id and data-field attrs to your page for draft mode${_RST}\n`)
  } else {
    console.log(`arc scaffold block: updated ${path.relative(process.cwd(), typesFile)}`)
    console.log(`arc scaffold block: created ${path.relative(process.cwd(), editorFile)}`)
    console.log(`arc scaffold block: created ${path.relative(process.cwd(), widgetFile)}`)
  }
}

