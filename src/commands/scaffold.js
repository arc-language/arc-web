function generateBlockWidget(type, fields) {
  const widgetName = type.charAt(0).toUpperCase() + type.slice(1) + 'Block'
  const paramList = ['id: Int', 'type: String', ...fields.map(f => `${f.name}: ${f.type}${f.optional ? '?' : ''}`)]
  const elLines = fields.map(f => {
    if (f.type === 'Bool') {
      return `    if ${f.name}\n      col data-field="${f.name}" "✓"`
    }
    if (f.type === 'Text') {
      return `    text class="block-${type}-${f.name}" data-field="${f.name}" "{${f.name}}"`
    }
    return `    heading class="block-${type}-${f.name}" data-field="${f.name}" "{${f.name}}"`
  }).join('\n')

  return `widget ${widgetName}(${paramList.join(', ')})
  col class="block-${type}" data-block-id="{id}" data-block-type="{type}"
${elLines}
`
}

